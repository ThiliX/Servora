package com.servora.common.tenant;

import java.util.UUID;
import org.slf4j.MDC;
import org.springframework.jdbc.core.simple.JdbcClient;
import org.springframework.stereotype.Component;
import org.springframework.transaction.support.TransactionSynchronization;
import org.springframework.transaction.support.TransactionSynchronizationManager;

/**
 * Sets the PostgreSQL settings that Row-Level Security policies read.
 *
 * <p>Every value is set with {@code set_config(name, value, true)}, which is transaction-local:
 * PostgreSQL discards it at commit or rollback, so a pooled connection never carries one request's
 * context into the next. Calling these methods outside a transaction is a programming error and
 * fails fast, because the setting would otherwise be lost immediately.
 *
 * <p>This is the only class that may set these values.
 */
@Component
public class TenantContext {

    private final JdbcClient jdbc;

    public TenantContext(JdbcClient jdbc) {
        this.jdbc = jdbc;
    }

    /** Identifies the authenticated user. Lets the user see their own membership rows. */
    public void bindUser(UUID userId) {
        set("app.user_id", userId.toString());
    }

    /**
     * Scopes the transaction to one tenant. Call only with a tenant ID the backend has validated:
     * after a membership check, for a tenant ID generated by the server, or for a tenant resolved
     * from a presented invitation token.
     */
    public void bindTenant(UUID tenantId) {
        set("app.tenant_id", tenantId.toString());
        // Log lines written while this transaction runs name the workspace. The value is removed
        // when the transaction ends, like the database setting itself.
        MDC.put(MDC_TENANT, tenantId.toString());
        if (TransactionSynchronizationManager.isSynchronizationActive()) {
            TransactionSynchronizationManager.registerSynchronization(new TransactionSynchronization() {
                @Override
                public void afterCompletion(int status) {
                    MDC.remove(MDC_TENANT);
                }
            });
        }
    }

    /** Log key for the workspace bound to the current transaction. */
    public static final String MDC_TENANT = "tenant_id";

    /** Lets the transaction read the single invitation that matches a presented token. */
    public void bindInvitationTokenHash(String tokenHash) {
        set("app.invitation_token_hash", tokenHash);
    }

    /**
     * Lets the transaction read the single widget whose public key was presented by a public
     * widget request. The widget's own tenant is bound afterwards, from that row (ADR-017).
     */
    public void bindWidgetKey(String publicKey) {
        set("app.widget_public_key", publicKey);
    }

    /**
     * Lets the outbox dispatcher read pending events of every tenant. Call only from the outbox
     * dispatcher: it runs outside any request and must bind the event tenant before writing.
     */
    public void enableOutboxDispatch() {
        set("app.outbox_dispatcher", "on");
    }

    /**
     * Lets the transaction read workspace metadata, subscriptions and usage of every tenant. Call
     * only from the platform admin service, after binding the user: the policies also require that
     * user to be in {@code platform_admins} (ADR-019).
     */
    public void enablePlatformAdmin() {
        set("app.platform_admin", "on");
    }

    /**
     * Lets the retention job list the workspaces that have a retention period. It must bind each
     * workspace before reading or deleting any of its data.
     */
    public void enableRetentionJob() {
        set("app.retention_job", "on");
    }

    private void set(String name, String value) {
        if (!TransactionSynchronizationManager.isActualTransactionActive()) {
            throw new IllegalStateException("Tenant context must be set inside a transaction");
        }
        jdbc.sql("SELECT set_config(:name, :value, true)")
                .param("name", name)
                .param("value", value)
                .query(String.class)
                .single();
    }
}
